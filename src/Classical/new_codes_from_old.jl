"""
$(TYPEDSIGNATURES)

Return the complementary subcode `C2 / C1` given `C1 ⊆ C2`.
"""
function /(C2::AbstractLinearCode, C1::AbstractLinearCode)
    C1.F == C2.F || throw(ArgumentError("Codes must be over the same field."))
    C1 ⊆ C2 || throw(ArgumentError("C1 is not a subcode of C2."))
    
    G1 = generator_matrix(C1)
    G2 = generator_matrix(C2)
    
    # Use the ultra-fast linear algebra quotient bypass
    Q = _quotient_space(G1, G2)
    
    # The resulting code is a subcode of C2, so its distance is bounded by C2's distance
    lb = ismissing(C2.d) ? C2.l_bound : C2.d
    cache = Dict{Symbol, Any}(:G => Q)
    
    return LinearCode(C1.F, C1.n, nrows(Q), missing, lb, C1.n, cache)
end
