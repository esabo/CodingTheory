"""
$(TYPEDSIGNATURES)

Return the residue code of `C` with respect to a codeword `c` (Construction A).
If `c` has weight `w`, this produces an `[n - w, k - 1, d']` code where 
`d' >= d - w + w / q`.
"""
function construction_A(C::AbstractLinearCode, c::Union{Vector{Int}, Vector{<:CTFieldElem}})
    c ∈ C || throw(ArgumentError("The vector must be a codeword of C."))
    
    # Find the support (indices of non-zero elements)
    S = findall(!iszero, c)
    w = length(S)
    w > 0 || throw(ArgumentError("Cannot apply Construction A using the zero codeword."))
    
    # Shortening on the first index of the support drops the dimension to k - 1
    # Puncturing on the remaining support coordinates removes the rest of the word
    C_short = shorten(C, S[1])
    C_res = puncture(C_short, S[2:end])
    
    # Inject theoretical Griesmer step bounds
    q = order(C.F)
    base_d = ismissing(C.d) ? C.l_bound : C.d
    d_lower = base_d - w + ceil(Int, w / q)
    
    # Safely clamp and apply the theoretical bound
    if d_lower > C_res.l_bound
        C_res.l_bound = min(d_lower, C_res.u_bound)
    end
    
    return C_res
end
residue_code(C::AbstractLinearCode, c) = construction_A(C, c)

"""
$(TYPEDSIGNATURES)

Return the code obtained by applying Construction B (also known as Construction Y1) 
using a codeword `h` of the dual code. Shortens `C` on the support of `h`, 
dropping the dimension by `s - 1` instead of `s`.
"""
function construction_B(C::AbstractLinearCode, h::Union{Vector{Int}, Vector{<:CTFieldElem}})
    h ∈ dual(C) || throw(ArgumentError("The vector must be a codeword of the dual of C."))
    
    S = findall(!iszero, h)
    s = length(S)
    s > 0 || throw(ArgumentError("Cannot apply Construction B using the zero codeword."))
    
    # The mathematical properties of shortening on a dual word guarantees 
    # the dimension drops by at most s - 1. Distance is preserved.
    C_new = shorten(C, S)
    
    base_d = ismissing(C.d) ? C.l_bound : C.d
    if base_d > C_new.l_bound
        C_new.l_bound = min(base_d, C_new.u_bound)
    end
    
    return C_new
end
construction_Y1(C::AbstractLinearCode, h) = construction_B(C, h)
construction_Y(C::AbstractLinearCode, h) = construction_B(C, h)

"""
$(TYPEDSIGNATURES)

Return the code obtained by applying Construction B2 to a binary code `C` 
using a dual codeword `h` of weight `s` and a parameter `j` such that `2j + 1 < s`.
"""
function construction_B2(C::AbstractLinearCode, h::Union{Vector{Int}, Vector{<:CTFieldElem}}, j::Int)
    Int(order(C.F)) == 2 || throw(ArgumentError("Construction B2 is only defined for binary codes."))
    h ∈ dual(C) || throw(ArgumentError("The vector must be a codeword of the dual of C."))
    
    S = findall(!iszero, h)
    s = length(S)
    2j + 1 < s || throw(ArgumentError("Parameter j must satisfy 2j + 1 < weight(h) (currently $s)."))
    j >= 0 || throw(ArgumentError("Parameter j must be non-negative."))
    
    # Partition the support: shorten on the first part, puncture on the second
    T = S[1 : s - 2j - 1]
    U = S[s - 2j : end]
    
    C_short = shorten(C, T)
    C_new = puncture(C_short, U)
    
    # Mathematical guarantee: puncturing 2j + 1 coordinates here only drops weight by 2j
    base_d = ismissing(C.d) ? C.l_bound : C.d
    d_lower = base_d - 2j
    
    if d_lower > C_new.l_bound
        C_new.l_bound = min(d_lower, C_new.u_bound)
    end
    
    return C_new
end

"""
$(TYPEDSIGNATURES)

Return the code generated by the construction X procedure.
"""
function construction_X(C1::AbstractLinearCode, C2::AbstractLinearCode, C3::AbstractLinearCode)
    C1 ⊆ C2 || throw(ArgumentError("The first code must be a subcode of the second in construction X."))
    are_equivalent(C1, C2) && throw(ArgumentError("The first code must be a proper subcode of the second in construction X."))
    C1.F == C2.F == C3.F || throw(ArgumentError("All codes must be over the same base ring in construction X."))
    C2.k == C1.k + dimension(C3) || throw(ArgumentError("The dimension of the second code must be the sum of the dimensions of the first and third codes."))

    G1 = generator_matrix(C1)
    G3 = generator_matrix(C3)
    G_quotient = generator_matrix(C2 / C1)
    
    G_new = vcat(hcat(G_quotient, G3), hcat(G1, zero_matrix(C1.F, C1.k, C3.n)))
    C = LinearCode(G_new)
    
    C.n == C1.n + C3.n || error("Something went wrong in construction X. Expected length $(C1.n + C3.n) but obtained length $(C.n)")

    if !ismissing(C1.d) && !ismissing(C2.d) && !ismissing(C3.d)
        C.d = minimum([C1.d, C2.d + C3.d])
        C.l_bound = C.d
        C.u_bound = C.d
    elseif ismissing(C.d)
        set_distance_lower_bound!(C, min(C1.l_bound, C2.l_bound + C3.l_bound))
    end
    return C
end

"""
$(TYPEDSIGNATURES)

Return the code generated by the construction X3 procedure.
"""
function construction_X3(C1::AbstractLinearCode, C2::AbstractLinearCode, C3::AbstractLinearCode, C4::AbstractLinearCode, C5::AbstractLinearCode)
    C1 ⊆ C2 || throw(ArgumentError("The first code must be a subcode of the second in construction X3."))
    are_equivalent(C1, C2) && throw(ArgumentError("The first code must be a proper subcode of the second in construction X3."))
    C2 ⊆ C3 || throw(ArgumentError("The second code must be a subcode of the third in construction X3."))
    are_equivalent(C2, C3) && throw(ArgumentError("The second code must be a proper subcode of the third in construction X3."))
    C1.F == C4.F == C5.F || throw(ArgumentError("All codes must be over the same base ring in construction X3."))
    C3.k == C2.k + C4.k || throw(ArgumentError("The dimension of the third code must be the sum of the dimensions of the second and fourth codes in construction X3."))
    C2.k == C1.k + C5.k || throw(ArgumentError("The dimension of the second code must be the sum of the dimensions of the first and fifth codes in construction X3."))

    C2_mod_C1 = C2 / C1
    C3_mod_C2 = C3 / C2
    F = C1.F

    G1 = generator_matrix(C1)
    G4 = generator_matrix(C4)
    G5 = generator_matrix(C5)
    
    G = vcat(hcat(G1, zero_matrix(F, C1.k, C4.n), zero_matrix(F, C1.k, C5.n)),
             hcat(generator_matrix(C2_mod_C1), G4, zero_matrix(F, C4.k, C5.n)),
             hcat(generator_matrix(C3_mod_C2), zero_matrix(F, C5.k, C4.n), G5))
             
    C = LinearCode(G)
    
    if !ismissing(C1.d) && !ismissing(C2.d) && !ismissing(C3.d) && !ismissing(C4.d) && !ismissing(C5.d) && ismissing(C.d)
        set_distance_lower_bound!(C, minimum([C1.d, C2.d + C4.d, C3.d + C5.d]))
    end
    return C
end

